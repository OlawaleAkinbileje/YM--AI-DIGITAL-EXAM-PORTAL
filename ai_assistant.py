import json
import re
import urllib.request
import urllib.error

def call_gemini_api(prompt: str, api_key: str) -> str:
    """
    Calls Google Gemini API using Python's standard library urllib.
    """
    if not api_key:
        raise ValueError("No Gemini API key provided. Please configure your key in Settings.")

    # Try gemini-1.5-flash endpoint
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key.strip()}"
    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt}
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.4,
            "topP": 0.95
        }
    }
    
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"}
    )
    
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            resp_data = json.loads(resp.read().decode("utf-8"))
            candidates = resp_data.get("candidates", [])
            if not candidates:
                raise ValueError("No response generated by Gemini model.")
            parts = candidates[0].get("content", {}).get("parts", [])
            if not parts:
                raise ValueError("Empty response received from Gemini.")
            return parts[0].get("text", "")
    except urllib.error.HTTPError as e:
        error_msg = e.read().decode("utf-8")
        try:
            error_json = json.loads(error_msg)
            message = error_json.get("error", {}).get("message", error_msg)
        except Exception:
            message = error_msg
        raise RuntimeError(f"Gemini API error ({e.code}): {message}")
    except Exception as e:
        raise RuntimeError(f"Connection failed: {str(e)}")

def generate_questions_with_ai(topic: str, count: int = 5, difficulty: str = "Intermediate", context: str = "", api_key: str = "") -> list:
    """
    Prompts Gemini to generate high-quality 4-option MCQs in structured JSON format.
    """
    count = max(1, min(20, count))
    system_instruction = f"""You are an expert curriculum and CBT examination author for digital skills, tech training, and professional certifications.
Generate exactly {count} multiple-choice question(s) for the topic: '{topic}'.
Target difficulty level: {difficulty}.
Additional context / course notes: '{context if context else 'Standard professional best practices'}'.

CRITICAL INSTRUCTIONS:
1. Each question must have exactly 4 plausible, well-written options: A, B, C, D.
2. Exactly one option must be the indisputably correct single best answer.
3. The other 3 options must be realistic distractors (avoid silly or obviously fake options).
4. Return ONLY valid JSON as an array of objects. Do not include markdown code blocks (```json), explanations, or preamble.

Expected JSON schema:
[
  {{
    "question": "Question text here?",
    "options": {{
      "A": "First option",
      "B": "Second option",
      "C": "Third option",
      "D": "Fourth option"
    }},
    "answer": "A"
  }}
]
"""

    response_text = call_gemini_api(system_instruction, api_key)
    
    # Clean possible markdown ticks (```json ... ```)
    clean_text = re.sub(r"^```(?:json)?", "", response_text.strip(), flags=re.MULTILINE)
    clean_text = re.sub(r"```$", "", clean_text.strip(), flags=re.MULTILINE).strip()

    try:
        parsed = json.loads(clean_text)
    except Exception:
        # Fallback regex extraction of JSON array
        match = re.search(r"\[\s*\{.*\}\s*\]", clean_text, re.DOTALL)
        if match:
            parsed = json.loads(match.group(0))
        else:
            raise ValueError("Could not parse AI response as JSON. Raw response: " + clean_text[:300])

    # Validate each question
    valid_questions = []
    for item in parsed:
        q_text = item.get("question", "").strip()
        opts = item.get("options", {})
        ans = item.get("answer", "A").strip().upper()
        if q_text and len(opts) == 4 and ans in ["A", "B", "C", "D"]:
            valid_questions.append({
                "question": q_text,
                "opt_a": opts.get("A", "").strip(),
                "opt_b": opts.get("B", "").strip(),
                "opt_c": opts.get("C", "").strip(),
                "opt_d": opts.get("D", "").strip(),
                "answer": ans
            })

    if not valid_questions:
        raise ValueError("AI generated response, but questions did not match standard format.")

    return valid_questions

def smart_parse_raw_text(raw_text: str) -> list:
    """
    Built-in offline intelligent parser for unstructured questions text.
    Handles formats like:
      1. Question text
      A. Option A
      B. Option B
      C. Option C
      D. Option D
      Answer: B (or facilitator key table at the end)
    """
    lines = raw_text.strip().split("\n")
    questions = []
    current_q = None

    # First check if there is an answer key table at the end
    embedded_keys = {}
    table_match = re.findall(r"\|\s*(\d+)\s*\|\s*([A-Da-d])\s*\|", raw_text)
    for q_num, ans in table_match:
        embedded_keys[int(q_num)] = ans.upper()

    for line in lines:
        line = line.strip()
        if not line or line.startswith("|") or line.startswith("Instructions:") or line.startswith("FACILITATOR ANSWER KEY"):
            continue

        # Match question start, e.g. "1. ..." or "Question 1: ..."
        q_match = re.match(r"^(?:Question\s+)?(\d+)[\.\:\)]\s+(.*)$", line, re.IGNORECASE)
        if q_match:
            if current_q and len(current_q["options"]) >= 4:
                questions.append(current_q)
            q_num = int(q_match.group(1))
            current_q = {
                "num": q_num,
                "question": q_match.group(2).strip(),
                "options": {},
                "answer": embedded_keys.get(q_num, "A")
            }
            continue

        # Match options: "A. ...", "A) ...", "[A] ..."
        opt_match = re.match(r"^\[?([A-D])\]?[\.\:\)]\s+(.*)$", line, re.IGNORECASE)
        if opt_match and current_q:
            opt_letter = opt_match.group(1).upper()
            opt_text = opt_match.group(2).strip()
            current_q["options"][opt_letter] = opt_text
            continue

        # Match inline answer, e.g. "Answer: B", "Ans: B"
        ans_match = re.match(r"^(?:Answer|Ans)[\s\:\-]+([A-D])", line, re.IGNORECASE)
        if ans_match and current_q:
            current_q["answer"] = ans_match.group(1).upper()
            continue

        # Continuation text
        if current_q:
            if not current_q["options"]:
                current_q["question"] += " " + line
            else:
                last_key = list(current_q["options"].keys())[-1]
                current_q["options"][last_key] += " " + line

    if current_q and len(current_q["options"]) >= 4:
        questions.append(current_q)

    # Format list for insertion
    formatted = []
    for q in questions:
        formatted.append({
            "question": q["question"],
            "opt_a": q["options"].get("A", ""),
            "opt_b": q["options"].get("B", ""),
            "opt_c": q["options"].get("C", ""),
            "opt_d": q["options"].get("D", ""),
            "answer": q.get("answer", "A")
        })

    return formatted

